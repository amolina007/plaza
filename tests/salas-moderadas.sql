begin;
do $$
declare a uuid; b uuid; c uuid; sid uuid; invitada uuid; r jsonb; slug_sala text; cuenta int;
begin
 select p.id into a from core.perfiles p where core.privacidad_capacidad(p.id,'comunidad') and not core.revision_inactiva(p.id) and not exists(select 1 from core.moderadores where usuario_id=p.id) and (select count(*) from core.salas where creada_por=p.id and activa)<3 order by p.id limit 1;
 select p.id into b from core.perfiles p where id<>a and core.privacidad_capacidad(p.id,'comunidad') and not core.revision_inactiva(p.id) and not exists(select 1 from core.moderadores where usuario_id=p.id) order by p.id limit 1;
 select p.id into c from core.perfiles p where id not in(a,b) and core.privacidad_capacidad(p.id,'comunidad') and not core.revision_inactiva(p.id) order by p.id limit 1;
 if a is null or b is null or c is null then raise exception 'Faltan perfiles elegibles para prueba'; end if;
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 set local role authenticated;
 sid:=core.plaza_dev_sala_crear('Prueba'||substr(replace(gen_random_uuid()::text,'-',''),1,12),'Comprobar salas reales','Respetar a todos','lectura','aprobacion');
 invitada:=core.plaza_dev_sala_crear('Invita'||substr(replace(gen_random_uuid()::text,'-',''),1,12),'Comprobar invitaciones','Respetar a todos','lectura','invitacion');
 perform set_config('request.jwt.claim.sub','',true);
 perform set_config('request.jwt.claims','{}',true);
 set local role anon;
 if exists(select 1 from jsonb_array_elements(core.plaza_dev_catalogo()) x where x->>'id'=invitada::text) then raise exception 'Catálogo anónimo expone invitación'; end if;
 if not exists(select 1 from jsonb_array_elements(core.plaza_dev_catalogo()) x where x->>'id'=sid::text) then raise exception 'Sala anunciada no visible'; end if;
 begin perform core.plaza_dev_panel(sid); raise exception 'Anónimo consultó panel'; exception when insufficient_privilege then null; end;
 reset role;
 set local role authenticated;
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 if not core.plaza_dev_mod(sid) or not core.puedo_ver_sala(sid) then raise exception 'Creador sin acceso/moderación'; end if;
 select x->>'slug' into slug_sala from jsonb_array_elements(core.plaza_dev_catalogo()) x where x->>'id'=sid::text;
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 if exists(select 1 from jsonb_array_elements(core.plaza_dev_catalogo()) x where x->>'id'=invitada::text) then raise exception 'Invitación visible a desconocido'; end if;
 begin perform core.plaza_dev_ingresar(sid,false,''); raise exception 'Aceptó reglas falsas'; exception when invalid_parameter_value then null; end;
 if core.plaza_dev_ingresar(sid,true,'Me interesa leer')<>'pendiente' then raise exception 'No pendiente'; end if;
 if core.puedo_ver_sala(sid) then raise exception 'Pendiente con acceso'; end if;
 begin perform core.unirme_a_sala(sid); raise exception 'Bypass por unirme'; exception when insufficient_privilege then null; end;
 select count(*) into cuenta from core.entrar_a_canal(slug_sala);
 if cuenta<>0 then raise exception 'Bypass por nombre'; end if;
 begin perform core.enviar_mensaje_sala(sid,'Mensaje no autorizado'); raise exception 'Pendiente pudo escribir'; exception when invalid_parameter_value or insufficient_privilege then null; end;
 begin perform core.plaza_dev_panel(sid); raise exception 'Panel de otro'; exception when insufficient_privilege then null; end;
 begin perform core.plaza_dev_configurar(sid,'abierta','Otras reglas'); raise exception 'Cambió acceso ajeno'; exception when insufficient_privilege then null; end;
 perform core.plaza_dev_favorito(sid,true);
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 r:=core.plaza_dev_panel(sid);
 if jsonb_array_length(r->'solicitudes')<>1 then raise exception 'Solicitud no registrada'; end if;
 perform core.plaza_dev_decidir(sid,b,'aceptar','Participación aprobada');
 perform core.plaza_dev_decidir(sid,b,'advertir','Cuida el lenguaje');
 perform core.plaza_dev_decidir(sid,b,'silenciar','Pausa de una hora');
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 if not core.puedo_ver_sala(sid) then raise exception 'Aprobado sin acceso'; end if;
 r:=core.plaza_dev_estado_propio(sid);
 if r->>'silencio_hasta' is null or jsonb_array_length(r->'avisos')<>2 then raise exception 'Avisos/silencio ausentes'; end if;
 begin perform core.enviar_mensaje_sala(sid,'Mensaje silenciado'); raise exception 'Silencio no aplicado en Core'; exception when insufficient_privilege then null; end;
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 perform core.plaza_dev_decidir(sid,b,'habilitar','Pausa terminada');
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 perform core.enviar_mensaje_sala(sid,'Mensaje permitido tras pausa');
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 perform core.plaza_dev_decidir(sid,b,'expulsar','Reincidencia en la sala');
 perform core.plaza_dev_decidir(invitada,c,'invitar','Invitación de prueba');
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 if core.puedo_ver_sala(sid) then raise exception 'Expulsado retuvo lectura'; end if;
 begin perform core.plaza_dev_ingresar(sid,true,''); raise exception 'Expulsado reingresó'; exception when insufficient_privilege then null; end;
 perform set_config('request.jwt.claim.sub',c::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',c,'role','authenticated')::text,true);
 if not exists(select 1 from jsonb_array_elements(core.plaza_dev_catalogo()) x where x->>'id'=invitada::text) then raise exception 'No ve invitación'; end if;
 if core.puedo_ver_sala(invitada) then raise exception 'Invitación permite leer antes de aceptar reglas'; end if;
 perform core.plaza_dev_ingresar(invitada,true,'Acepto');
 if not core.puedo_ver_sala(invitada) then raise exception 'No aceptó invitación'; end if;
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 perform core.plaza_dev_decidir(invitada,c,'nombrar','Ayudará a moderar');
 perform set_config('request.jwt.claim.sub',c::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',c,'role','authenticated')::text,true);
 if not core.plaza_dev_mod(invitada) then raise exception 'No nombró moderador'; end if;
 perform core.plaza_dev_configurar(invitada,'abierta','Reglas nuevas de prueba');
 begin perform core.plaza_dev_decidir(invitada,a,'expulsar','Intento inválido'); raise exception 'Expulsó a creador'; exception when insufficient_privilege then null; end;
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 if core.plaza_dev_ingresar(invitada,true,'Ingreso abierto')<>'aceptada' then raise exception 'Ingreso abierto falla'; end if;
 reset role;
 if has_table_privilege('authenticated','core.plaza_dev_solicitudes','select') or has_function_privilege('anon','core.plaza_dev_decidir(uuid,uuid,text,text)','execute') then raise exception 'Permisos excesivos'; end if;
end $$;
select 'OK: creación, aprobación, invitación, moderación, reglas, acceso y bloqueos Core' resultado;
rollback;
